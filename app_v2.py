def _ev_entry(head, body):
    return (
        f'<div class="saltus-ev-entry">'
        f'<div class="saltus-ev-entry-head">{html.escape(head)}</div>'
        f'<div class="saltus-ev-entry-body">{html.escape(body)}</div>'
        f"</div>"
    )


def _evidence_html_encounters(df):
    ordered = df.sort_values("date", ascending=False)
    if ordered.empty:
        return '<p class="saltus-ev-empty">None on record.</p>'
    return "".join(
        _ev_entry(f"{format_human_date(row['date'])} — {row['encounter_type']}", str(row["note_text"]))
        for _, row in ordered.iterrows()
    )


def _evidence_html_labs(df):
    if df.empty:
        return '<p class="saltus-ev-empty">None on record.</p>'
    parts = []
    for test_name, group in df.groupby("test_name"):
        lines = "; ".join(
            f"{format_human_date(row['date'])}: {row['value']:g} {row['unit']}"
            for _, row in group.sort_values("date", ascending=False).iterrows()
        )
        parts.append(_ev_entry(str(test_name), lines))
    return "".join(parts)


def _evidence_html_medications(df):
    if df.empty:
        return '<p class="saltus-ev-empty">None on record.</p>'
    parts = []
    for _, row in df.sort_values("date_started", ascending=False).iterrows():
        status = "Active" if pd.isna(row["date_stopped"]) else f"Stopped {format_human_date(row['date_stopped'])}"
        head = f"{row['medication_name']} — {row['dose']}"
        body = f"Started {format_human_date(row['date_started'])} · {status}"
        if pd.notna(row["notes"]) and str(row["notes"]).strip():
            body += f" · {row['notes']}"
        parts.append(_ev_entry(head, body))
    return "".join(parts)


def _evidence_html_observations(df):
    if df.empty:
        return '<p class="saltus-ev-empty">None on record.</p>'
    return "".join(
        _ev_entry(
            f"{format_human_date(row['date'])} — {row['observation_type']}",
            f"{row['value']} {row['unit']}",
        )
        for _, row in df.sort_values("date", ascending=False).iterrows()
    )


def _evidence_html_referrals(df):
    if df.empty:
        return '<p class="saltus-ev-empty">None on record.</p>'
    parts = []
    for _, row in df.sort_values("date", ascending=False).iterrows():
        head = f"{format_human_date(row['date'])} — {row['specialty']}"
        body = str(row["status"])
        if pd.notna(row["notes"]) and str(row["notes"]).strip():
            body += f" · {row['notes']}"
        parts.append(_ev_entry(head, body))
    return "".join(parts)


