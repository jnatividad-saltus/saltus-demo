def select_trajectory_test(labs_df):
    """Picks the lab test with the richest history (>=3 results) as the one
    factual trend worth remembering. Generic selection, not patient-specific."""
    if labs_df.empty:
        return None
    counts = labs_df.groupby("test_name").size()
    qualifying = counts[counts >= 3]
    if qualifying.empty:
        return None
    top_count = qualifying.max()
    tied_names = sorted(qualifying[qualifying == top_count].index.tolist())
    test_name = tied_names[0]
    group = labs_df[labs_df["test_name"] == test_name].sort_values("date")
    return test_name, group


def format_trajectory_values(values, unit):
    if unit == "%":
        return " → ".join(f"{v:g}%" for v in values)
    return " → ".join(f"{v:g} {unit}" for v in values)


# Which direction is clinically better, per test -- used only to choose
# plain wording (improving/rising/declining) for an already-computed,
# strictly-monotonic 3-point trend. Deterministic: applied to the rule
# engine's own numeric output, never to language generated by the LLM
# (Ask Saltus's own Rule 8 governs that separately). A single reversal in
# the last three values returns None rather than guessing a word.
LOWER_IS_BETTER_TESTS = {"HbA1c", "LDL", "creatinine", "natriuretic peptide", "urine albumin-to-creatinine ratio"}
HIGHER_IS_BETTER_TESTS = {"eGFR"}


def trend_direction_word(test_name, values):
    if len(values) < 2:
        return None
    diffs = [b - a for a, b in zip(values, values[1:])]
    if all(d < 0 for d in diffs):
        direction = "down"
    elif all(d > 0 for d in diffs):
        direction = "up"
    else:
        return None
    if test_name in LOWER_IS_BETTER_TESTS:
        return "improving" if direction == "down" else "rising"
    if test_name in HIGHER_IS_BETTER_TESTS:
        return "improving" if direction == "up" else "declining"
    return None


def build_review_tiles(labs_df, encounters_df, all_meds_df, trajectory):
    """Builds the Visit Prep review tiles as (headline, detail) pairs. Final
    display order (Jane's review, July 24, 2026): trend, monitoring, care
    gap, continuity (dose/stop discrepancies) -- HbA1c trend leads per
    diabetes guideline convention, with the continuity/discrepancy flag
    last regardless of its color accent. Up to 4 tiles -- one per
    category, whichever categories actually have findings for this
    patient. Wording is derived from the same underlying deterministic
    rules as before; only the presentation (short headline + separate
    detail line, instead of one flat sentence) is new for P-03."""
    tiles = []

    trajectory_test_name = None
    if trajectory is not None:
        trajectory_test_name, group = trajectory
        last_three = group.tail(3)
        unit = last_three.iloc[-1]["unit"]
        values_text = format_trajectory_values(last_three["value"].tolist(), unit)
        word = trend_direction_word(trajectory_test_name, last_three["value"].tolist())
        headline = f"{trajectory_test_name} {word} over time" if word else f"{trajectory_test_name} trend to watch"
        tiles.append(
            {
                "category": "Clinical trajectory",
                "headline": headline,
                "detail": values_text,
                "date": last_three.iloc[-1]["date"],
                "prominent": False,
                "test_name": trajectory_test_name,
                "direction_word": word,
            }
        )

    lab_findings = rule_lab_recency(labs_df)
    monitoring_candidates = [f for f in lab_findings if f["test_name"] != trajectory_test_name]
    if monitoring_candidates:
        chosen = sorted(monitoring_candidates, key=lambda f: f["source_date"])[0]
        tiles.append(
            {
                "category": "Monitoring context",
                "headline": f"{chosen['test_name']} monitoring overdue",
                "detail": f"Last result {format_human_date(chosen['source_date'])}",
                "date": chosen["date"],
                "prominent": False,
                "test_name": chosen["test_name"],
            }
        )

    dose_findings = rule_medication_dose_mentions(all_meds_df, encounters_df)
    stop_findings = rule_medication_stop_mentions(all_meds_df, encounters_df)
    if dose_findings:
        top = sorted(dose_findings, key=lambda f: f["date"])[0]
        tiles.append(
            {
                "category": "Continuity issue",
                "headline": f"Possible {top['med_name']} dose discrepancy",
                "detail": f"{top['note_dose']} mg vs {top['list_dose']} mg",
                "date": top["date"],
                "prominent": True,
                "med_name": top["med_name"],
                "continuity_kind": "dose",
            }
        )
    elif stop_findings:
        top = stop_findings[0]
        # Short headline + detail, matching the other tiles' length (Jane's
        # review, July 24, 2026) -- the rule engine's full sentence
        # ("X remains active in the medication list; a <date> encounter
        # note mentions stopping it") was overflowing the fixed-width
        # card. Full sentence is unchanged and still available verbatim
        # via the Medications/Encounters entries in Supporting Record;
        # only the tile's own text got more concise.
        tiles.append(
            {
                "category": "Continuity issue",
                "headline": f"Possible {top['med_name']} discontinuation",
                "detail": f"Still listed active despite {format_human_date(top['date'])} note",
                "date": top["date"],
                "prominent": True,
                "med_name": top.get("med_name"),
                "continuity_kind": "stop",
            }
        )

    gap_findings = rule_encounter_gaps(encounters_df)
    if gap_findings:
        chosen = sorted(gap_findings, key=lambda f: f["date"], reverse=True)[0]
        earlier = date.fromisoformat(chosen["source_date"].split(" → ")[0])
        later = date.fromisoformat(chosen["source_date"].split(" → ")[1])
        months = relativedelta(later, earlier).years * 12 + relativedelta(later, earlier).months
        # Worded as a gap BETWEEN two specific past encounters, with the
        # date range spelled out -- not "no encounter for N months," which
        # reads like "months since the last visit" and gets confused with
        # the unrelated "N months ago" figure in the left rail (Jane's
        # review, July 24, 2026: same-sounding but different numbers).
        tiles.append(
            {
                "category": "Recent visit gap",
                "headline": "Care gap",
                "detail": (
                    f"{months}-month gap between visits "
                    f"({earlier.strftime('%b %Y')}–{later.strftime('%b %Y')})"
                ),
                "date": chosen["date"],
                "prominent": False,
            }
        )

    # Reversed per Jane's follow-up (July 24, 2026): by diabetes guideline
    # convention HbA1c is the primary metric, so the trend tile leads;
    # medication continuity/discrepancy flags now sit last rather than
    # first, regardless of how alarming their color accent looks.
    CATEGORY_PRIORITY = {
        "Clinical trajectory": 0,
        "Monitoring context": 1,
        "Recent visit gap": 2,
        "Continuity issue": 3,
    }
    tiles.sort(key=lambda t: CATEGORY_PRIORITY.get(t["category"], 9))

    return tiles[:4]


def compute_y_domain(values, target=None):
    """Includes the target line in the min/max pool when given (Jane's
    review, July 24, 2026): with only 2 data points close in value (e.g.
    Blood Pressure at 136/138), the domain used to be computed from just
    those 2 points, so a target well outside that tight range (like 130)
    rendered off-screen entirely -- and the trend line itself had almost
    no vertical room to read as an actual graph, just a near-flat segment
    hugging the top of the card. Folding the target into the range fixes
    both: the target line is always visible, and there's real vertical
    spread to draw."""
    pool = list(values) + ([target] if target is not None else [])
    vmin, vmax = min(pool), max(pool)
    if vmax == vmin:
        pad = max(abs(vmax) * 0.1, 1.0)
    else:
        pad = (vmax - vmin) * 0.25
    return vmin - pad, vmax + pad


