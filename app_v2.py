def egfr_stage(value):
    """KDIGO CKD staging -- same sourced values verified in the P-02 design
    spec (Diabetes Canada / KDIGO), rebuilt here since app_v2.py was reset
    to a clean copy of app.py and this lookup didn't exist yet."""
    if value >= 90:
        return "G1"
    if value >= 60:
        return "G2"
    if value >= 45:
        return "G3a"
    if value >= 30:
        return "G3b"
    if value >= 15:
        return "G4"
    return "G5"


