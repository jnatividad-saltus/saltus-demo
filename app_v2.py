def rule_lab_recency(labs_df):
    findings = []
    if labs_df.empty:
        return findings
    latest_per_test = labs_df.sort_values("date").groupby("test_name", as_index=False).tail(1)
    for _, row in latest_per_test.sort_values("test_name").iterrows():
        result_date = date.fromisoformat(row["date"])
        if result_date < LAB_RECENCY_CUTOFF:
            findings.append(
                {
                    "category": "Laboratory",
                    "test_name": row["test_name"],
                    "finding": f"Most recent {row['test_name']} is from {row['date']}.",
                    "date": row["date"],
                    "prominent": False,
                    "source_type": "Laboratory result",
                    "source_date": row["date"],
                    "source_text": f"{row['test_name']}: {row['value']:g} {row['unit']} recorded on {row['date']}.",
                }
            )
    return findings


def rule_encounter_gaps(encounters_df):
    """Flags gaps exceeding the threshold whose END falls within the most
    recent three years of the fictional dataset (anchored to July 2026), even
    if the gap began earlier."""
    findings = []
    if encounters_df.empty:
        return findings
    ordered = encounters_df.assign(_d=encounters_df["date"].apply(date.fromisoformat)).sort_values("_d")
    rows = ordered.to_dict("records")
    for prev_row, curr_row in zip(rows, rows[1:]):
        earlier, later = prev_row["_d"], curr_row["_d"]
        if later < ENCOUNTER_GAP_WINDOW_START:
            continue
        if later > earlier + relativedelta(months=ENCOUNTER_GAP_THRESHOLD_MONTHS):
            findings.append(
                {
                    "category": "Encounter timing",
                    "finding": f"No recorded encounters between {earlier.isoformat()} and {later.isoformat()}.",
                    "date": later.isoformat(),
                    "prominent": False,
                    "source_type": "Encounter history",
                    "source_date": f"{earlier.isoformat()} → {later.isoformat()}",
                    "source_text": (
                        f"Previous encounter ({earlier.isoformat()}, {prev_row['encounter_type']}): "
                        f"{prev_row['note_text']} "
                        f"Next encounter ({later.isoformat()}, {curr_row['encounter_type']}): "
                        f"{curr_row['note_text']}"
                    ),
                }
            )
    return findings


def rule_medication_stop_mentions(all_medications_df, encounters_df):
    findings = []
    if all_medications_df.empty or encounters_df.empty:
        return findings
    active = all_medications_df[all_medications_df["date_stopped"].isna()]
    seen = set()
    for _, med in active.iterrows():
        med_name = med["medication_name"]
        for _, enc in encounters_df.iterrows():
            note = enc["note_text"]
            if med_name.lower() in note.lower() and "stop" in note.lower():
                key = (med_name, enc["date"])
                if key not in seen:
                    seen.add(key)
                    findings.append(
                        {
                            "category": "Medication",
                            "finding": (
                                f"{med_name} remains active in the medication list; "
                                f"a {enc['date']} encounter note mentions stopping it."
                            ),
                            "date": enc["date"],
                            "prominent": True,
                            "source_type": "Encounter note",
                            "source_date": enc["date"],
                            "source_text": enc["note_text"],
                            "med_name": med_name,
                        }
                    )
    return findings


_DOSE_MG_RE = re.compile(r"(\d+(?:\.\d+)?)\s*mg")


def rule_medication_dose_mentions(all_medications_df, encounters_df):
    """Flags an active medication whose currently-listed dose differs from a
    dose explicitly written in a later encounter note about that same
    medication -- e.g. the medication list says 500 mg but a visit note says
    it was increased to 1000 mg. Deterministic regex extraction only, same
    discipline as rule_medication_stop_mentions above: never infers which
    value is "current," only states both and names the discrepancy (mirrors
    Ask Saltus system-prompt Rule 6). New rule added July 24, 2026 (P-03
    Build Plan Section 8, Screen 2) -- approved by Jane before being written,
    per the standing practice of not adding new clinical-finding detection
    logic without sign-off (see docs/P-02/P-02-design-spec.md, post-review
    gap closure note)."""
    findings = []
    if all_medications_df.empty or encounters_df.empty:
        return findings
    active = all_medications_df[all_medications_df["date_stopped"].isna()]
    seen = set()
    for _, med in active.iterrows():
        med_name = med["medication_name"]
        list_match = _DOSE_MG_RE.search(str(med["dose"]))
        if not list_match:
            continue
        list_dose = list_match.group(1)
        for _, enc in encounters_df.sort_values("date").iterrows():
            note = enc["note_text"]
            if med_name.lower() not in note.lower():
                continue
            note_match = _DOSE_MG_RE.search(note)
            if not note_match:
                continue
            note_dose = note_match.group(1)
            if note_dose == list_dose:
                continue
            key = (med_name, enc["date"])
            if key in seen:
                continue
            seen.add(key)
            findings.append(
                {
                    "category": "Medication",
                    "finding": (
                        f"{med_name.capitalize()} is listed at {med['dose']}; "
                        f"a {enc['date']} note mentions {note_dose} mg."
                    ),
                    "date": enc["date"],
                    "prominent": True,
                    "source_type": "Encounter note",
                    "source_date": enc["date"],
                    "source_text": enc["note_text"],
                    "list_dose": list_dose,
                    "note_dose": note_dose,
                    "med_name": med_name,
                }
            )
    return findings


def compute_review_items(labs_df, encounters_df, all_meds_df):
    """All findings from all rules, unabridged -- used for the Supporting Record."""
    items = []
    items.extend(rule_medication_stop_mentions(all_meds_df, encounters_df))
    items.extend(rule_medication_dose_mentions(all_meds_df, encounters_df))
    items.extend(rule_lab_recency(labs_df))
    items.extend(rule_encounter_gaps(encounters_df))
    return items


