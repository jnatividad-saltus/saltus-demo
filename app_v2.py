def ask_saltus(client, context, question):
    """One independent question-answer call -- no chat history is kept or
    sent across questions."""
    system_prompt = SALTUS_SYSTEM_PROMPT_TEMPLATE.format(context=context, question=question)
    response = client.messages.create(
        model=ASK_SALTUS_MODEL,
        max_tokens=4096,
        system=system_prompt,
        messages=[{"role": "user", "content": question}],
    )
    answer = "".join(block.text for block in response.content if block.type == "text")
    return answer, response.usage


