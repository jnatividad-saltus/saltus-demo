TAB_LABELS = [("prep", "Visit Preparation"), ("timeline", "Timeline"), ("ask", "Ask Saltus")]


def render_tab_bar(active_tab):
    """Manually built tab bar (Build Plan Section 7): st.tabs() doesn't
    expose which tab is active to code outside the tab body, which the
    persistent left rail and (later) the tab-aware right rail both need.
    Returns the active tab key, updated if a tab button was clicked.

    Fix (July 24, 2026): the first version wrapped each button in a
    st.markdown() div, but Streamlit doesn't nest markdown and widgets that
    way -- each st.* call becomes its own sibling element, so the wrapping
    div was always empty and the active-tab CSS never reached the button.
    Fixed using the same working pattern already proven on the "Back to
    EMR" button: a real st.container(key=...), which Streamlit does assign
    a stable, targetable CSS class to (.st-key-<key>).

    Left-aligned (Jane's review, July 24, 2026): three equal-width
    columns with use_container_width=True stretched each tab across a
    third of the whole row, spreading them out with big gaps instead of
    clustering together on the left like the approved reference. Columns
    are now sized just wide enough for each label, use_container_width
    is dropped so the button hugs its own text instead of stretching,
    and one large spacer column at the end absorbs the rest of the row
    so the empty space lands after "Ask Saltus," not between the tabs."""
    cols = st.columns([1.7, 1.0, 1.15, 4.5], gap="small")
    for col, (key, label) in zip(cols, TAB_LABELS):
        with col:
            with st.container(key=f"tabwrap_{key}"):
                if st.button(label, key=f"tab_btn_{key}"):
                    active_tab = key
    # Specificity fix (July 24, 2026): the base "strip default button
    # border" rule in inject_css() targets
    # ".st-key-tabbar_row div[data-testid='stButton'] button", which is
    # MORE specific (2 classes/attrs + 2 elements) than the old active-tab
    # override here (1 class + 1 element) -- so the active tab's blue
    # color/underline was silently losing the CSS specificity contest and
    # never rendering, regardless of source order. This selector now
    # matches that same shape (class + class + attr + element) so it wins.
    # :focus/:active included explicitly (not just the base, unstated
    # state) because the active tab is, by definition, the one that was
    # just clicked -- so it's sitting in :focus when this renders, which
    # is exactly the state Streamlit's default red would otherwise win.
    st.markdown(
        f"<style>.st-key-tabbar_row .st-key-tabwrap_{active_tab} "
        f'div[data-testid="stButton"] button, '
        f".st-key-tabbar_row .st-key-tabwrap_{active_tab} "
        f'div[data-testid="stButton"] button:focus, '
        f".st-key-tabbar_row .st-key-tabwrap_{active_tab} "
        f'div[data-testid="stButton"] button:focus:not(:active), '
        f".st-key-tabbar_row .st-key-tabwrap_{active_tab} "
        f'div[data-testid="stButton"] button:active {{'
        f"color:{BLUE} !important; font-weight:700 !important; "
        f"border-bottom:2px solid {BLUE} !important; outline:none !important;}}</style>",
        unsafe_allow_html=True,
    )
    return active_tab


