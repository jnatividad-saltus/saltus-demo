def build_synthesis_lines(patient_row, tiles, primary_condition_name):
    first_name = patient_row["name"].split()[0]
    gap_tile = next((t for t in tiles if t["category"] == "Recent visit gap"), None)
    trend_tile = next((t for t in tiles if t["category"] == "Clinical trajectory"), None)
    monitor_tile = next((t for t in tiles if t["category"] == "Monitoring context"), None)
    continuity_tile = next((t for t in tiles if t["category"] == "Continuity issue"), None)

    if gap_tile:
        suffix = f" on {primary_condition_name.lower()}" if primary_condition_name else ""
        line1 = f"{first_name} is due for a follow-up{suffix} after a prolonged care gap."
    elif primary_condition_name:
        line1 = f"{first_name} is here for a scheduled review of {primary_condition_name.lower()}."
    else:
        line1 = f"{first_name} is here for a scheduled visit."

    clauses = []
    if trend_tile:
        word = trend_tile.get("direction_word")
        clauses.append(f"{trend_tile['test_name']} is {word}" if word else f"{trend_tile['test_name']} is being watched")
    if monitor_tile:
        clauses.append(f"{monitor_tile['test_name']} monitoring is overdue")
    if continuity_tile:
        if continuity_tile.get("continuity_kind") == "dose":
            clauses.append("medication records conflict")
        else:
            clauses.append("a medication continuity item needs a closer look")

    line2 = None
    if len(clauses) == 1:
        line2 = clauses[0].capitalize() + "."
    elif len(clauses) >= 2:
        line2 = clauses[0].capitalize() + ", but " + " and ".join(clauses[1:]) + "."

    # Dropped the generic "Clarifying these items will help ensure safe,
    # continuous, and effective care" line per Jane's review (July 24,
    # 2026) -- it didn't add information beyond the tiles/line2 above it.
    return [line for line in [line1, line2] if line]


