def assemble_patient_context(
    patient_row, all_conditions_df, encounters_df, labs_df, observations_df, all_meds_df, referrals_df
):
    """Formats every retrieved row for one patient into a dated, labeled text
    block for the model. This is the full grounded context -- no rows from
    any other patient are included."""
    lines = []

    years = int(patient_row["family_physician_relationship_years"])
    lines.append("PATIENT")
    lines.append(f"Name: {patient_row['name']}")
    lines.append(f"Age: {int(patient_row['age'])}, Sex: {patient_row['sex'].capitalize()}")
    lines.append(f"Followed in this practice for {years} year{'s' if years != 1 else ''}.")

    lines.append("\nCONDITIONS")
    if all_conditions_df.empty:
        lines.append("None on record.")
    else:
        for _, row in all_conditions_df.sort_values("date_recorded").iterrows():
            lines.append(f"- {row['date_recorded']}: {row['condition_name']} (status: {row['status']})")

    lines.append("\nENCOUNTERS")
    if encounters_df.empty:
        lines.append("None on record.")
    else:
        for _, row in encounters_df.sort_values("date").iterrows():
            lines.append(f"- {row['date']} ({row['encounter_type']}): {row['note_text']}")

    lines.append("\nLAB RESULTS")
    if labs_df.empty:
        lines.append("None on record.")
    else:
        for _, row in labs_df.sort_values("date").iterrows():
            lines.append(f"- {row['date']}: {row['test_name']} = {row['value']:g} {row['unit']}")

    lines.append("\nOBSERVATIONS")
    if observations_df.empty:
        lines.append("None on record.")
    else:
        for _, row in observations_df.sort_values("date").iterrows():
            lines.append(f"- {row['date']}: {row['observation_type']} = {row['value']} {row['unit']}")

    lines.append("\nMEDICATIONS (including discontinued)")
    if all_meds_df.empty:
        lines.append("None on record.")
    else:
        for _, row in all_meds_df.sort_values("date_started").iterrows():
            status = "active" if pd.isna(row["date_stopped"]) else f"stopped {row['date_stopped']}"
            line = f"- {row['medication_name']}: {row['dose']}, started {row['date_started']}, {status}."
            if pd.notna(row["notes"]) and str(row["notes"]).strip():
                line += f" Notes: {row['notes']}"
            lines.append(line)

    lines.append("\nREFERRALS")
    if referrals_df.empty:
        lines.append("None on record.")
    else:
        for _, row in referrals_df.sort_values("date").iterrows():
            line = f"- {row['date']} ({row['specialty']}): {row['status']}."
            if pd.notna(row["notes"]) and str(row["notes"]).strip():
                line += f" Notes: {row['notes']}"
            lines.append(line)

    return "\n".join(lines)


