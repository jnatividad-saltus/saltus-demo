    series = {}

    hba1c = labs_df[labs_df["test_name"] == "HbA1c"].sort_values("date")
    series["HbA1c"] = {
        "target_label": "Target",
        "target_text": "≤7.0%",
        "target_line": 7.0,
        "out_of_range": lambda v: v > 7.0,
        "points": [(r["date"], r["value"], f"{r['value']:g}%") for _, r in hba1c.iterrows()],
    }

    ldl = labs_df[labs_df["test_name"] == "LDL"].sort_values("date")
    series["LDL Cholesterol"] = {
        "target_label": "Target",
        "target_text": "<77 mg/dL",
        "target_line": 77.0,
        "out_of_range": lambda v: v > 77.0,
        "points": [(r["date"], r["value"], f"{r['value']:g} mg/dL") for _, r in ldl.iterrows()],
    }

    egfr = labs_df[labs_df["test_name"] == "eGFR"].sort_values("date")
    egfr_points = [(r["date"], r["value"], f"{r['value']:g}") for _, r in egfr.iterrows()]
    series["eGFR"] = {
        "target_label": "Stage",
        "target_text": egfr_stage(egfr_points[-1][1]) if egfr_points else "—",
        "target_line": None,
        "out_of_range": lambda v: v < 60,
        "points": egfr_points,
    }

    bp = observations_df[observations_df["observation_type"] == "blood pressure"].sort_values("date")
    bp_points = []
    for _, r in bp.iterrows():
        sys_v = _bp_systolic(r["value"])
        if sys_v is None:
            continue
        bp_points.append((r["date"], sys_v, str(r["value"])))
    series["Blood Pressure"] = {
        "target_label": "Target",
        "target_text": "<130/80",
        "target_line": 130.0,
        "out_of_range": lambda v: v >= 130,
        "points": bp_points,
    }

    return series


