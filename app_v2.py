def build_patient_story(
    all_conditions_df, encounters_df, labs_df, all_meds_df, trajectory, records_max, primary_condition_name=None
):
    """Derives the horizontal stepper shown at the top of Timeline (mock:
    Diagnosis -> Treatment -> Improvement -> Care Gap -> Return to Care ->
    Today), built only from real dated records already used elsewhere in
    the app -- earliest condition, earliest medication start, the same
    trajectory test used in Visit Prep, and the same rule_encounter_gaps
    check used for the "Recent visit gap" tile. A stage is included only
    when the underlying data actually supports it -- e.g. a patient with
    no detected care gap simply gets a shorter arc, never a fabricated one.
    Jane's request, July 24, 2026."""
    stages = []
    trajectory_test_name = None
    trend_word = None
    gap_info = None

    if not all_conditions_df.empty:
        # Uses the *primary* condition's own recorded date when known
        # (Jane's pressure-test review, July 24, 2026) -- previously this
        # was always the earliest condition on file regardless of what
        # the condition, which could be a different condition than the
        # one named in the story text right below it (e.g. Michael's
        # "Diagnosis" stage showed 2021/hypertension while the narrative
        # was about type 2 diabetes, recorded 2023). Falls back to the
        # overall earliest condition if the primary one isn't found.
        primary_matches = (
            all_conditions_df[all_conditions_df["condition_name"] == primary_condition_name]
            if primary_condition_name else all_conditions_df.iloc[0:0]
        )
        source = primary_matches if not primary_matches.empty else all_conditions_df
        first_condition = source.sort_values("date_recorded").iloc[0]
        d = first_condition["date_recorded"]
        stages.append({"key": "diagnosis", "label": "Diagnosis", "sub_label": d[:4], "icon": "fa-solid fa-notes-medical"})

    if not all_meds_df.empty:
        first_med = all_meds_df.sort_values("date_started").iloc[0]
        d = first_med["date_started"]
        stages.append({"key": "treatment", "label": "Treatment", "sub_label": d[:4], "icon": "fa-solid fa-pills"})

    if trajectory is not None:
        trajectory_test_name, group = trajectory
        # Same last-3-points window Visit Prep's tile uses (build_review_tiles)
        # -- deliberately, so the two screens never disagree about whether
        # this patient's trend counts as "improving" (Jane's cross-screen
        # consistency check, July 24, 2026).
        last_three = group.tail(3)
        trend_word = trend_direction_word(trajectory_test_name, last_three["value"].tolist())
        if trend_word == "improving":
            mid_row = last_three.iloc[len(last_three) // 2]
            d = mid_row["date"]
            stages.append({"key": "improvement", "label": "Improvement", "sub_label": d[:4], "icon": "fa-solid fa-arrow-trend-up"})

    gap_findings = rule_encounter_gaps(encounters_df)
    if gap_findings:
        chosen = sorted(gap_findings, key=lambda f: f["date"], reverse=True)[0]
        earlier = date.fromisoformat(chosen["source_date"].split(" → ")[0])
        later = date.fromisoformat(chosen["source_date"].split(" → ")[1])
        months = relativedelta(later, earlier).years * 12 + relativedelta(later, earlier).months
        stages.append({
            "key": "care_gap", "label": "Care Gap",
            "sub_label": f"{earlier.strftime('%b %Y')} – {later.strftime('%b %Y')}",
            "icon": "fa-solid fa-calendar-days",
        })
        stages.append({
            "key": "return_to_care", "label": "Return to Care",
            "sub_label": format_human_date(later.isoformat()),
            "icon": "fa-solid fa-user-doctor",
        })
        gap_info = {"earlier": earlier, "later": later, "months": months}

    if records_max:
        stages.append({
            "key": "today", "label": "Today", "sub_label": "Current Visit",
            "icon": "fa-solid fa-circle-dot", "current": True,
        })

    return stages, trajectory_test_name, trend_word, gap_info


def build_story_lines(patient_row, primary_condition_name, trajectory_test_name, trend_word, gap_info, years_followed):
    """Same short-narrative pattern as build_synthesis_lines (Visit
    Preparation), reused for the Timeline story box per Jane's request
    (July 24, 2026): a personalized 1-2 line arc instead of a generic
    title, built only from the same deterministic facts driving the
    stepper above it."""
    first_name = patient_row["name"].split()[0]
    sex = str(patient_row.get("sex", "")).lower()
    pronoun = "she" if sex == "female" else ("he" if sex == "male" else "they")

    suffix = f" for {primary_condition_name.lower()}" if primary_condition_name else ""
    plural = "s" if years_followed != 1 else ""
    line1 = f"{first_name} has been followed{suffix} for {years_followed} year{plural} in this practice."

    clauses = []
    if trajectory_test_name and trend_word == "improving":
        clauses.append(f"{trajectory_test_name} has improved with treatment")
    if gap_info:
        clauses.append(
            f"a {gap_info['months']}-month gap in care followed before {pronoun} returned in "
            f"{gap_info['later'].strftime('%b %Y')}"
        )

    line2 = None
    if len(clauses) == 1:
        line2 = clauses[0][0].upper() + clauses[0][1:] + "."
    elif len(clauses) >= 2:
        line2 = clauses[0][0].upper() + clauses[0][1:] + ", and " + " ".join(clauses[1:]) + "."

    return [l for l in [line1, line2] if l]


