_ISO_DATE_RE = re.compile(r"\b(\d{4})-(\d{2})-(\d{2})\b")


def format_human_date(iso_str):
    """'2025-02-14' -> 'Feb 14, 2025'. Presentation only; does not touch
    underlying stored values."""
    d = date.fromisoformat(iso_str)
    return f"{d.strftime('%b')} {d.day}, {d.year}"


def format_relative(iso_str, reference=REFERENCE_DATE):
    """'2025-02-14' -> '5 months ago', relative to the fixed demo reference
    date. Presentation only."""
    d = date.fromisoformat(iso_str)
    delta = relativedelta(reference, d)
    total_months = delta.years * 12 + delta.months
    if total_months < 1:
        if delta.days <= 0:
            return "today"
        return f"{delta.days} day{'s' if delta.days != 1 else ''} ago"
    if total_months < 24:
        return f"{total_months} month{'s' if total_months != 1 else ''} ago"
    years = total_months // 12
    return f"{years} year{'s' if years != 1 else ''} ago"


def humanize_dates_in_text(text):
    """Rewrites any yyyy-mm-dd substrings in free text to 'Mon D, YYYY'.
    Used only to reformat model output for display -- does not change the
    words, values, or claims in the text."""

    def repl(match):
        try:
            return format_human_date(match.group(0))
        except ValueError:
            return match.group(0)

    return _ISO_DATE_RE.sub(repl, text)


