def compute_records_reviewed_range(
    all_conditions_df, encounters_df, labs_df, observations_df, all_meds_df, referrals_df
):
    """Earliest and latest dated record on file for this patient, across
    every table -- the actual grounding range for the trust statement, never
    a fixed/hardcoded date pair."""
    dates = []
    dates += all_conditions_df["date_recorded"].dropna().tolist()
    dates += encounters_df["date"].dropna().tolist()
    dates += labs_df["date"].dropna().tolist()
    dates += observations_df["date"].dropna().tolist()
    dates += referrals_df["date"].dropna().tolist()
    dates += all_meds_df["date_started"].dropna().tolist()
    dates += all_meds_df["date_stopped"].dropna().tolist()
    if not dates:
        return None, None
    return min(dates), max(dates)


