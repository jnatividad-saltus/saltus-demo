def parse_answer_sections(answer_text):
    """Splits a '## Header' formatted answer into ordered (header, body)
    pairs. Falls back to a single unlabeled section if the model did not use
    the requested headers (rule 10 asks for them, but never overrides
    rules 1-9, so a plain-text fallback answer must still display cleanly).
    Presentation-only: does not alter the model's words."""
    pattern = re.compile(r"^##\s+(.+?)\s*$", re.MULTILINE)
    matches = list(pattern.finditer(answer_text))
    if not matches:
        return [(None, answer_text.strip())]
    sections = []
    for i, m in enumerate(matches):
        header = m.group(1).strip()
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(answer_text)
        body = answer_text[start:end].strip()
        if body:
            sections.append((header, body))
    return sections if sections else [(None, answer_text.strip())]


def render_bullet_body(text):
    """Renders '- fact' lines as spaced, one-fact-per-row bullets for
    scanning. Falls back to a plain paragraph if the model didn't use
    bullets. Presentation only -- does not alter the model's words."""
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    bullets = [ln[2:].strip() for ln in lines if ln.startswith("- ")]
    if not bullets:
        return f'<div style="font-size:0.94rem; line-height:1.5;">{text}</div>'
    rows = "".join(
        '<div style="display:flex; gap:8px; margin-bottom:8px; font-size:0.94rem; '
        'line-height:1.4;"><span style="flex-shrink:0; color:var(--saltus-muted);">•</span>'
        f"<span>{b}</span></div>"
        for b in bullets
    )
    return f"<div>{rows}</div>"


_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.?!])\s+(?=[A-Z(])|;\s*")


def render_answer_bullets(text, color):
    """Splits the Direct Answer into one bullet per sentence -or- clause
    (Jane's review, July 24, 2026) so a multi-fact answer reads as a
    scannable list instead of one dense paragraph -- same
    sentence-boundary splitting approach as render_bullet_body's
    fallback, just applied proactively here since the model's Direct
    Answer is written as prose, not "- " lines. Also splits on ";" since
    the model sometimes joins two facts with a semicolon instead of a
    period -- the semicolon itself is dropped (redundant once each
    clause is its own bullet) and the clause's first letter is
    capitalized so it reads cleanly as a standalone line; no words are
    added, removed, or reordered. A single-sentence answer isn't split
    into a list of one."""
    sentences = [s.strip() for s in _SENTENCE_SPLIT_RE.split(text.strip()) if s.strip()]
    sentences = [s[0].upper() + s[1:] if s[:1].isalpha() else s for s in sentences]
    if len(sentences) <= 1:
        return f'<div style="font-size:1.05rem; font-weight:700; color:{color}; line-height:1.5;">{text}</div>'
    rows = "".join(
        '<div style="display:flex; gap:8px; margin-bottom:8px; font-size:1.05rem; '
        f'font-weight:700; color:{color}; line-height:1.4;"><span style="flex-shrink:0;">•</span>'
        f"<span>{s}</span></div>"
        for s in sentences
    )
    return f"<div>{rows}</div>"


def render_ask_saltus_answer(answer_text):
    """Renders ONLY the direct answer (bold blue, one bullet per fact) --
    this lives inside the caller's green question/answer box, so it has
    no border/background of its own (Jane's review, July 24, 2026: the
    top box should show question + answer only). Why / What Remains
    Unclear used to render here too, nested inside that same green box;
    they now render separately via render_ask_saltus_supporting, each in
    its own card, so the top box doesn't turn into a box-within-a-box.
    Returns section_map (the remaining named sections) so the caller can
    pass it straight to render_ask_saltus_supporting without re-parsing.
    Presentation only -- does not alter any word the model produced."""
    sections = parse_answer_sections(answer_text)
    section_map = {header: body for header, body in sections if header}
    fallback = next((body for header, body in sections if header is None), None)

    direct = section_map.pop("Direct Answer", None)
    answer_body = direct if direct else fallback
    if answer_body:
        st.markdown(
            render_answer_bullets(humanize_dates_in_text(answer_body), BLUE),
            unsafe_allow_html=True,
        )
    return section_map


